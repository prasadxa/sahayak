/** Look up a UI string: the language, then English, then the key itself. */
export function translate(
  lang: string,
  key: string,
  vars?: Record<string, string>
): string {
  let str = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars ?? {})) {
    str = str.replaceAll(`{${k}}`, v);
  }
  return str;
}

interface I18nContextValue {
  lang: string;
  setLang: (code: string) => void;
  t: (key: string, vars?: Record<string, string>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: DEFAULT_LANGUAGE,
  setLang: () => {},
  t: (key, vars) => translate(DEFAULT_LANGUAGE, key, vars),
});

export function I18nProvider({
  children,
  initialLang = DEFAULT_LANGUAGE,
}: {
  children: ReactNode;
  /** Language read from the cookie on the server, so the first render matches. */
  initialLang?: string;
}) {
  const [lang, setLangState] = useState(initialLang);

  const setLang = useCallback((code: string) => {
    setLangState(code);
    document.cookie = `${LANGUAGE_COOKIE}=${encodeURIComponent(code)};path=/;max-age=31536000`;
    document.documentElement.lang = code;
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string>) => translate(lang, key, vars),
    [lang]
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
